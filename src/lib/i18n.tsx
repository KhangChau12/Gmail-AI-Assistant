const dictionaries: Record<Language, Record<MessageKey, string>> = { en, vi };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

interface I18nContext {
  lang: Language;
  t: Translate;
  setLang: (lang: Language) => void;
}

const Context = createContext<I18nContext | null>(null);

export function I18nProvider({ initial, children }: { initial: Language; children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(initial);

  const t = useCallback<Translate>(
    (key, vars) => {
      let text = dictionaries[lang][key] ?? en[key];
      if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
      return text;
    },
    [lang],
  );

  const setLang = useCallback((next: Language) => {
    setLangState(next);
    document.documentElement.lang = next;
    // Stored server-side because the AI uses it for summaries and replies.
    void fetch('/api/settings', { method: 'PUT', body: JSON.stringify({ language: next }) });
  }, []);

  const value = useMemo(() => ({ lang, t, setLang }), [lang, t, setLang]);
  return <Context.Provider value={value}>{children}</Context.Provider>;
}

export function useI18n() {
  const ctx = useContext(Context);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
